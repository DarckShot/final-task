import {chromium,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {once} from 'node:events';
import {createPool,taskStore} from '../src/db.js';
import {createApp} from '../src/app.js';
if (!process.env.TEST_DATABASE_URL) throw new Error('TEST_DATABASE_URL required (disposable PostgreSQL database)');
const pool=createPool(process.env.TEST_DATABASE_URL);
const config={login:`ui_${randomUUID()}`,fullName:'Проверка интерфейса',token:randomUUID()};
const server=createApp({config,store:taskStore(pool,config.login)}).listen(0,'127.0.0.1');
await once(server,'listening');
let browser;
try {
  browser=await chromium.launch({channel:process.env.PLAYWRIGHT_CHANNEL || 'chrome',headless:true});
  const page=await browser.newPage();
  const errors=[]; page.on('pageerror',error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  await page.getByLabel('Токен доступа',{exact:true}).fill('wrong'); await page.getByRole('button',{name:'Войти',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('Неверный токен');
  await page.getByLabel('Токен доступа',{exact:true}).fill(config.token); await page.getByRole('button',{name:'Войти',exact:true}).click();
  await expect(page.locator('#author')).toContainText(config.fullName);
  await expect(page.locator('#author')).toContainText(config.login);
  await page.getByLabel('Название дела',{exact:true}).first().fill('<script>alert(1)</script>');
  await page.getByRole('button',{name:'Добавить дело',exact:true}).click();
  await expect(page.locator('.task-title')).toHaveText('<script>alert(1)</script>');
  await page.getByRole('button',{name:'Изменить: <script>alert(1)</script>',exact:true}).click();
  await page.locator('#edit-title').fill('Переименовано'); await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await expect(page.locator('.task-title')).toHaveText('Переименовано');
  await page.getByRole('checkbox',{name:'Выполнено: Переименовано',exact:true}).check();
  await expect(page.locator('#count')).toHaveText('Выполнено 1 из 1');
  await page.getByRole('checkbox',{name:'Выполнено: Переименовано',exact:true}).uncheck();
  await expect(page.locator('#count')).toHaveText('Выполнено 0 из 1');
  const {rows:[row]}=await pool.query('SELECT id FROM tasks WHERE owner_login=$1',[config.login]);
  await pool.query('UPDATE tasks SET title=$1 WHERE id=$2',['Изменено SQL',row.id]);
  await page.getByRole('button',{name:'Обновить',exact:true}).click(); await expect(page.locator('.task-title')).toHaveText('Изменено SQL');
  page.once('dialog',dialog => dialog.accept()); await page.getByRole('button',{name:'Удалить: Изменено SQL',exact:true}).click();
  await expect(page.locator('#empty')).toBeVisible();
  await page.getByRole('button',{name:'Добавить итоговую работу',exact:true}).click();
  await expect(page.locator('.task-title')).toHaveText(`Итоговая работа 24.10.2026: ${config.login}`);
  await page.getByLabel('Группа (runId)',{exact:true}).fill('other'); await page.getByRole('button',{name:'Показать',exact:true}).click();
  await expect(page.locator('#empty')).toBeVisible();
  await page.setViewportSize({width:375,height:812});
  if (await page.evaluate(() => document.documentElement.scrollWidth>innerWidth)) throw new Error('Horizontal overflow at 375px');
  await page.getByRole('button',{name:'Выйти',exact:true}).click(); await expect(page.locator('#login-panel')).toBeVisible();
  await expect(page.locator('#token')).toBeFocused();
  const storage=await page.evaluate(() => [localStorage.length,sessionStorage.length]); expect(storage).toEqual([0,0]);
  expect(errors).toEqual([]);
  console.log('Browser PASS: login, author, XSS-safe title, rename, done/undone, SQL refresh, delete, manual task, runId, mobile, logout, in-memory token');
} finally {
  await browser?.close(); await new Promise(resolve => server.close(resolve));
  await pool.query('DELETE FROM tasks WHERE owner_login=$1',[config.login]); await pool.end();
}
